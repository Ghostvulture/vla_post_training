"""Resume two-round X-VLA updates with data, replay and optimizer audits."""

import argparse
import copy
import json
import math
import random
from pathlib import Path

import numpy as np
import torch
from peft import LoraConfig, PeftModel, get_peft_model, get_peft_model_state_dict, set_peft_model_state_dict
from XPolicyLab.policy.X_VLA.model import XVLA, XVLAProcessor

from flow_policy import encode_inputs, flow_step
from round_data import load_episodes, make_chunks


def main():
    parser = argparse.ArgumentParser()
    for key in ("base", "data", "result", "output"):
        parser.add_argument(f"--{key}", type=Path, required=True)
    parser.add_argument("--method", choices=("rl", "fsft"), required=True)
    parser.add_argument("--resume", type=Path)
    parser.add_argument("--steps", type=int, default=16)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--round", type=int, required=True)
    parser.add_argument("--behavior-policy", required=True)
    parser.add_argument("--audit-resume", action="store_true")
    args = parser.parse_args()
    if args.steps < 1:
        parser.error("steps must be positive")
    args.output.mkdir(parents=True, exist_ok=False)
    torch.manual_seed(args.seed)
    random.seed(args.seed)
    rng = random.Random(args.seed)
    net = XVLA.from_pretrained(str(args.base), torch_dtype=torch.float32).cuda()
    processor = XVLAProcessor.from_pretrained(str(args.base / "processor"))
    episodes = load_episodes(args.data, json.loads(args.result.read_text()), net.num_actions)
    chunks, skip = make_chunks(episodes, net.num_actions, args.method)
    if args.round > 1 and not args.resume:
        raise ValueError("Later rounds require a resumable checkpoint")
    for row in episodes:
        if args.round > 1 and (row.get("behavior_policy") != args.behavior_policy or row.get("round") != args.round):
            raise ValueError("Second-round episode lacks matching behavior policy/round metadata")
    if args.resume:
        expected = args.resume / ("lora" if args.method == "rl" else "export")
        if Path(args.behavior_policy).resolve() != expected.resolve():
            raise ValueError("Second-round data must be generated by the resumed policy")
    head = [k for k, _ in net.named_modules() if k.startswith("transformer.blocks.") and k.endswith(".attn.qkv")]
    vlm = [k for k, _ in net.named_modules() if k.startswith("vlm.language_model.model.encoder.layers.") and k.endswith((".self_attn.q_proj", ".self_attn.v_proj"))]
    if len(head) != 24 or len(vlm) != 24:
        raise ValueError("Unexpected X-VLA architecture")
    lr = 2e-6 if args.method == "rl" else 1e-4
    if args.resume:
        model = PeftModel.from_pretrained(net, args.resume / "lora", is_trainable=True)
    elif args.method == "rl":
        model = get_peft_model(net, LoraConfig(r=3, lora_alpha=6, target_modules=head+vlm,
            rank_pattern={k: 2 for k in vlm}, alpha_pattern={k: 4 for k in vlm}))
    else:
        model = get_peft_model(net, LoraConfig(r=4, lora_alpha=8, target_modules=head))
    model.eval()
    params = [p for p in model.parameters() if p.requires_grad]
    assert sum(p.numel() for p in params) == 393216
    optimizer = torch.optim.AdamW(params, lr=lr, weight_decay=0)
    settings = dict(method=args.method, learning_rate=lr, base=str(args.base.resolve()), seed=args.seed,
                    trainable_parameters=393216, batch_chunks=4)
    start = 0
    completed = 0

    def capture():
        return dict(optimizer=optimizer.state_dict(), sampler=rng.getstate(), python=random.getstate(),
                    torch=torch.get_rng_state(), cuda=torch.cuda.get_rng_state_all(),
                    completed_updates=completed, settings=settings)

    def restore(state):
        if state["settings"] != settings:
            raise ValueError("Continuation settings differ from checkpoint")
        optimizer.load_state_dict(state["optimizer"])
        rng.setstate(state["sampler"])
        random.setstate(state["python"])
        torch.set_rng_state(state["torch"].cpu())
        torch.cuda.set_rng_state_all([x.cpu() for x in state["cuda"]])

    if args.resume:
        state = torch.load(args.resume / "resume.pt", map_location="cpu", weights_only=False)
        restore(state)
        start = state["planned_step"]
        completed = state["completed_updates"]

    audit = dict(settings=settings, round=args.round, source=str(args.result), behavior_policy=args.behavior_policy,
        resume=str(args.resume) if args.resume else None, planned_updates=args.steps, completed_updates=0,
        skip_reason=skip, chunks=len(chunks), successes=sum(r["success"] for r in episodes),
        episodes=[{k: v for k, v in r.items() if k != "paths"} for r in episodes],
        env_steps=sum(r["steps"] for r in episodes), updates=[], replay={}, action_conversion={})

    def write_audit():
        (args.output / "training.json").write_text(json.dumps(audit, indent=2))

    def save(step):
        directory = args.output / f"step-{step:03d}"
        directory.mkdir()
        model.save_pretrained(directory / "lora")
        state = capture()
        state["planned_step"] = step
        torch.save(state, directory / "resume.pt")
        (directory / "training.json").write_text(json.dumps(audit, indent=2))
        return directory

    def tensors(chunk):
        with np.load(chunk["path"], allow_pickle=False) as ex:
            if "behavior_policy" in ex and ex["behavior_policy"].item() != args.behavior_policy:
                raise ValueError(f"Behavior checkpoint mismatch: {chunk['path']}")
            inputs, state = encode_inputs(processor, ex["image"], ex["prompt"].item(), ex["proprio"], "cuda")
            if args.method == "rl":
                xt, old, raw = [torch.from_numpy(ex[k]).cuda().unsqueeze(0) for k in ("xt", "mean", "raw")]
                scale = torch.from_numpy(ex["scale"]).to(old)
                if scale.shape != (20,) or not torch.isfinite(scale).all() or not (scale > 0).all():
                    raise ValueError("Invalid behavior scale")
                return inputs, state, xt, old, raw, scale
            action = torch.from_numpy(ex["action"]).cuda().unsqueeze(0) if "action" in ex else net.action_space.postprocess(torch.from_numpy(ex["raw"]).cuda().unsqueeze(0).clone())
            if action.shape != (1, net.num_actions, 20) or not torch.isfinite(action).all():
                raise ValueError("Invalid FSFT action target")
            inputs["image_input"] = inputs.pop("pixel_values")
            inputs["proprio"] = state
            inputs["domain_id"] = torch.zeros(1, device="cuda", dtype=torch.long)
            return inputs, action

    # Validate every saved block before training; replay must use the generating policy.
    replay_max, replay_ratio_max, checked, converted = 0., 0., 0, 0
    with torch.no_grad():
        for chunk in chunks:
            if args.method == "rl":
                inputs, state, xt, old, raw, scale = tensors(chunk)
                mean = flow_step(net, net.forward_vlm(**inputs), state, xt, state.new_full((1,), .1))
                delta = ((mean-old)/scale)[:, :chunk["used"]]
                ratio_log = ((((raw-old)/scale)[:, :chunk["used"]])*delta - .5*delta.square()).sum().item()
                replay_max = max(replay_max, (mean-old).abs().max().item())
                replay_ratio_max = max(replay_ratio_max, abs(ratio_log))
                if not torch.allclose(mean, old, rtol=1e-5, atol=2e-5) or abs(ratio_log) > .05:
                    raise ValueError(f"Behavior replay mismatch: {chunk['path']}, log_ratio={ratio_log}")
                checked += 1
            else:
                with np.load(chunk["path"], allow_pickle=False) as ex:
                    if "raw" in ex:
                        raw = torch.from_numpy(ex["raw"]).cuda().unsqueeze(0)
                        action = net.action_space.postprocess(raw.clone())
                        expected = raw.clone()
                        expected[..., (9, 19)] = expected[..., (9, 19)].sigmoid()
                        torch.testing.assert_close(action, expected, rtol=0, atol=0)
                        if "action" in ex:
                            torch.testing.assert_close(action[0].cpu(), torch.from_numpy(ex["action"]), rtol=0, atol=0)
                        converted += 1
                tensors(chunk)
    audit["replay"] = dict(blocks=checked, max_abs_mean_error=replay_max, max_abs_log_ratio=replay_ratio_max)
    audit["action_conversion"] = dict(raw_blocks=converted, transform="official postprocess: sigmoid grippers 9/19, other channels unchanged")
    write_audit()
    save(start)

    def update():
        optimizer.zero_grad()
        batch = rng.sample(chunks, 4) if args.method == "rl" else [rng.choice(chunks) for _ in range(4)]
        logs, samples, total = [], [], 0.
        for chunk in batch:
            samples.append(dict(block=str(chunk["path"].relative_to(args.data)), episode_id=chunk["episode_id"], used=chunk["used"], advantage=chunk["advantage"]))
            if args.method == "rl":
                inputs, state, xt, old, raw, scale = tensors(chunk)
                mean = flow_step(net, net.forward_vlm(**inputs), state, xt, state.new_full((1,), .1))
                shift = ((mean-old)/scale)[:, :chunk["used"]]
                z = ((raw-old)/scale)[:, :chunk["used"]]
                log_ratio = (z*shift - .5*shift.square()).sum()
                ratio = log_ratio.clamp(-20, 20).exp()
                adv = chunk["advantage"]
                loss = -torch.minimum(ratio*adv, ratio.clamp(.8, 1.2)*adv)
                logs.append(log_ratio.detach().item())
            else:
                inputs, action = tensors(chunk)
                loss = sum(model(**inputs, action=action).values())
            (loss / 4).backward()
            total += loss.item() / 4
        grad = torch.nn.utils.clip_grad_norm_(params, 1., error_if_nonfinite=True)
        optimizer.step()
        if not math.isfinite(total) or not all(torch.isfinite(p).all() for p in params):
            raise ValueError("Nonfinite training state")
        return dict(loss=total, grad_norm=grad.item(), log_ratios=logs, samples=samples)

    for index in range(1, args.steps + 1):
        step = start + index
        if not skip:
            if args.audit_resume and index == min(9, args.steps):
                # Reload saved weights, Adam moments and RNG; repeat the actual next update.
                before = copy.deepcopy(capture())
                weights = {k: v.detach().cpu().clone() for k, v in get_peft_model_state_dict(model).items()}
                resume_check = args.output / "resume-check.pt"
                torch.save(dict(state=before, weights=weights), resume_check)
                first = update()
                after = {k: v.detach().cpu().clone() for k, v in get_peft_model_state_dict(model).items()}
                first_opt = copy.deepcopy(optimizer.state_dict())
                first_torch_rng = torch.get_rng_state().clone()
                first_cuda_rng = [x.clone() for x in torch.cuda.get_rng_state_all()]
                saved = torch.load(resume_check, map_location="cpu", weights_only=False)
                set_peft_model_state_dict(model, saved["weights"])
                restore(saved["state"])
                record = update()
                if first != record:
                    raise ValueError("Resumed update samples/loss differ from continuous execution")
                max_difference = 0.
                for k, v in get_peft_model_state_dict(model).items():
                    max_difference = max(max_difference, (v.detach().cpu()-after[k]).abs().max().item())
                if max_difference != 0:
                    raise ValueError(f"Resume changed weights: {max_difference}")
                for key, state in first_opt["state"].items():
                    for field, value in state.items():
                        torch.testing.assert_close(value, optimizer.state_dict()["state"][key][field], rtol=0, atol=0)
                assert torch.equal(first_torch_rng, torch.get_rng_state())
                assert all(torch.equal(a, b) for a, b in zip(first_cuda_rng, torch.cuda.get_rng_state_all()))
                audit["resume_validation"] = dict(step=step, max_weight_difference=max_difference, optimizer_and_rng_exact=True)
                resume_check.unlink()
            else:
                record = update()
            completed += 1
            audit["completed_updates"] += 1
            audit["updates"].append(dict(step=step, **record))
        if index % 8 == 0 or index == args.steps:
            saved_dir = save(step)
        write_audit()
    if args.method == "fsft":
        # Preserve the unmerged checkpoint for continued optimization.
        # Merging changes arithmetic order; verify the exported policy on one stored input.
        probe = next((p for r in episodes for p in r["paths"]), None)
        with np.load(probe, allow_pickle=False) as ex:
            inputs, state = encode_inputs(processor, ex["image"], ex["prompt"].item(), ex["proprio"], "cuda")
            inputs["image_input"] = inputs.pop("pixel_values")
            inputs["proprio"] = state
            inputs["domain_id"] = torch.zeros(1, device="cuda", dtype=torch.long)
        with torch.no_grad(), torch.random.fork_rng(devices=[torch.cuda.current_device()]):
            reference = net.generate_actions(**inputs, steps=10)
        merged = model.merge_and_unload(safe_merge=True)
        with torch.no_grad(), torch.random.fork_rng(devices=[torch.cuda.current_device()]):
            exported = merged.generate_actions(**inputs, steps=10)
        torch.testing.assert_close(reference, exported, rtol=1e-4, atol=2e-5)
        audit["export_validation"] = dict(max_action_difference=(reference-exported).abs().max().item())
        export = saved_dir / "export"
        merged.save_pretrained(export, safe_serialization=True)
        (export / "processor").symlink_to((args.base / "processor").resolve())
    write_audit()


if __name__ == "__main__":
    main()
